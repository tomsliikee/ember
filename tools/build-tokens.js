#!/usr/bin/env node
// Generates the extension's colour and type values from the design system,
// so no value is typed by hand: extension/lib/tokens.js for drawing code and
// extension/stylesheet.css from tools/stylesheet.template.css.
//
// St has no CSS custom properties, so the template is written once with
// $token placeholders and expanded into one rule set per colour style and
// theme. The styles other than the default are derived from their seeds by
// tools/derive-styles and kept in tools/styles.json.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const system = JSON.parse(fs.readFileSync(path.join(root, 'toms-expressive-design', 'tokens.json'), 'utf8'));
const THEMES = system.color.themes.map(theme => theme.id);

function resolveColor(name, theme, seen = new Set()) {
    const token = system.color.tokens.find(t => t.name === name);
    if (!token || seen.has(name))
        throw new Error(`Unknown or circular colour token: ${name}`);
    seen.add(name);
    const value = typeof token.value === 'string' ? token.value : token.value[theme];
    const reference = /^\{(.+)\}$/.exec(value);
    return reference ? resolveColor(reference[1], theme, seen) : value;
}

const derived = JSON.parse(fs.readFileSync(path.join(__dirname, 'styles.json'), 'utf8'));
const STYLES = Object.keys(derived);

// A scheme is one style in one theme, named like "violet-dark". Roles a
// style does not derive (error, status, illustration) come from the design system.
const colors = {};
for (const style of STYLES) {
    for (const theme of THEMES) {
        const base = Object.fromEntries(system.color.tokens.map(t => [t.name, resolveColor(t.name, theme)]));
        const scheme = {...base, ...derived[style][theme]};
        colors[`${style}-${theme}`] = scheme;
    }
}

const px = value => Number.parseInt(value, 10);
const scale = group => Object.fromEntries(group.tokens.map(t => [t.name, px(t.value)]));
const sizes = {...scale(system.spacing), ...scale(system.radius), ...scale(system.size)};

// The width axis of a role is only stated in its usage note ("wdth 112").
const type = Object.fromEntries(system.type.groups.flatMap(group => group.styles).map(style => {
    const width = /wdth (\d+)/.exec(style.usage);
    return [style.name, {
        size: px(style.fontSize),
        weight: style.fontWeight,
        width: width ? Number(width[1]) : 100,
        italic: style.fontStyle === 'italic',
    }];
}));

const family = system.type.fonts[0].family;
const header = '// Generated by tools/build-tokens.js from toms-expressive-design/tokens.json. Do not edit.\n';

fs.writeFileSync(path.join(root, 'extension', 'lib', 'tokens.js'), `${header}
export const family = ${JSON.stringify(family)};

export const styles = ${JSON.stringify(STYLES)};

export const colors = ${JSON.stringify(colors, null, 4)};

export const sizes = ${JSON.stringify(sizes, null, 4)};

export const type = ${JSON.stringify(type, null, 4)};
`);

const template = fs.readFileSync(path.join(__dirname, 'stylesheet.template.css'), 'utf8');

function expand(css, scheme) {
    return css.replace(/\$([a-z0-9-]+)/g, (_, name) => {
        if (name in sizes)
            return `${sizes[name]}px`;
        if (!(name in colors[scheme]))
            throw new Error(`Unknown token in the template: ${name}`);
        return colors[scheme][name];
    });
}

// Rules above the marker carry no colour and are written once.
const [shared, themed] = template.split('/* themed */');
const sheets = Object.keys(colors).map(scheme =>
    expand(themed.replace(/\.em-popup/g, `.em-popup-${scheme}`), scheme).trim());
fs.writeFileSync(path.join(root, 'extension', 'stylesheet.css'),
    `${header.replace('//', '/*').replace('\n', ' */\n')}\n${expand(shared, Object.keys(colors)[0]).trim()}\n\n${sheets.join('\n\n')}\n`);
